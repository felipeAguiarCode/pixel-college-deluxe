const englishCache = new Map();
const englishOrdinal = (n) => n + ({ 1: 'st', 2: 'nd', 3: 'rd' }[n] || 'th');
function englishCopy(value) {
  const text = String(value ?? '');
  if (!text.trim()) return text;
  if (/^\s*time\s*$/i.test(text)) return text.replace(/time/i, text.includes('TIME') ? 'TEAM' : 'Team');
  if (englishCache.has(text)) return englishCache.get(text);
  const result = text
    .replace(/(\d+)[.](\d{3})(?=\D|$)/g, '$1,$2')
    .replace(/(\d+),(\d{1,2})(?=\D|$)/g, '$1.$2')
    .replace(/(\d+)\s*ª(?:\s+para\s+(?:o\s+)?|(?=\s|$))/gi, (label, n) => englishOrdinal(n) + (/\spara\s/i.test(label) ? ' & ' : ''))
    .replace(/(\d+)º\s+(quarto|Q)\b/gi, (_, n) => 'Q' + n)
    .replace(/Semana (\d+) de (\d+)/gi, (label, week, total) => label === label.toUpperCase() ? `WEEK ${week} OF ${total}` : `Week ${week} of ${total}`)
    .replace(/(\d+)º na (?=[A-Z\d])/g, (_, n) => `${englishOrdinal(n)} in `)
    .replace(/Lançar ([\d,.]+) jardas de passe/gi, 'Throw for $1 passing yards')
    .replace(/Lançar (\d+) passes para touchdown/gi, 'Throw $1 touchdown passes')
    .replace(/Correr ([\d,.]+) jardas/gi, 'Rush for $1 yards')
    .replace(/Marcar (\d+) touchdowns/gi, 'Score $1 touchdowns')
    .replace(/Conquistar (\d+) first downs/gi, 'Earn $1 first downs')
    .replace(/Acertar (\d+)% dos passes \(mín. 30 tentativas\)/gi, 'Complete $1% of passes (min. 30 attempts)')
    .replace(/No máximo (\d+) turnovers na temporada/gi, 'Limit the season to $1 turnovers')
    .replace(/Sofrer até (\d+) pontos por jogo/gi, 'Allow up to $1 points per game')
    .replace(/Fazer uma jogada de (\d+)\+ jardas/gi, 'Make a play of $1+ yards')
    .replace(/Marcar (\d+)\+ pontos em uma partida/gi, 'Score $1+ points in a game')
    .replace(/Vencer (\d+) jogos na temporada regular/gi, 'Win $1 regular-season games')
    .replace(/Vencer uma partida por (\d+)\+ pontos/gi, 'Win a game by $1+ points')
    .replace(/Chute convertido de (\d+) jardas/gi, 'Made a $1-yard kick')
    .replace(/Avanço de (\d+) jardas/gi, 'Gain of $1 yards')
    .replace(/soma (\d+) pontos/gi, 'scores $1 points')
    .replace(/Começa o Q(\d+)/gi, 'Quarter $1 starts')
    .replace(/FIM DO Q(\d+)/g, 'END OF Q$1')
    .replace(/TEMPORADA (\d+) CONCLUÍDA/g, 'SEASON $1 COMPLETE')
    .replace(/(\d+)\/3 cumpridas/gi, '$1/3 complete')
    .replace(englishPattern, (source) => {
      const translated = englishPhrases.get(source.toLowerCase()) || source;
      if (source === source.toUpperCase()) return translated.toUpperCase();
      return source[0] === source[0].toUpperCase() ? translated : translated[0].toLowerCase() + translated.slice(1);
    });
  if (englishCache.size >= 2000) englishCache.delete(englishCache.keys().next().value);
  englishCache.set(text, result);
  return result;
}
